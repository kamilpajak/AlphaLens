#!/usr/bin/env python
"""Phase-2/3 outcome join + inference for the Stage-1 retro gate-increment study.

Joins the Phase-1 blind labels (hash-pinned, generated by
``stage1_retro_label_pairs.py``) to the stored population-ladder outcomes and
runs the single pre-registered primary hypothesis test, per
`docs/research/stage1_retro_gate_increment_prereg_2026_08_19.md` (§8, §10-§12).

Locked parameters (pre-registered; do not change without a memo amendment):

* **Two-stage commit** — this script refuses to run unless the labels parquet
  sha256 equals the Stage-B committed value (``LABELS_SHA256``, pre-reg §11.2).
* **Primary (H1, CLEAN window only)** — one-sided KEPT − REFUSED > 0 on
  pair-cluster mean matured `market_excess_return`; matured = ``terminal``
  rows only; `market_excess_return` winsorized at 1% per leg (row-level,
  each leg separately; unwinsorized also reported); inference via a two-way
  (pair × brief-day) cluster bootstrap with 10,000 resamples.
* **Everything else is descriptive** — the DEV-window contrast, the
  ticker-level three-way split, the crowd-out share, and the refusal-reason
  taxonomy carry no hypothesis slot and no verdict vocabulary.
* **Power (Phase 3)** — one-sided two-sample normal-approximation power for
  the forward window, parameterized by the measured refusal rate and the
  CLEAN pair-level spread magnitude.

Usage::

    python apps/alphalens-research/scripts/stage1_retro_outcome_inference.py \\
        --labels <labels.parquet> \\
        --outcomes <ladder_outcomes.csv> \\
        --calls-log <phase1_calls.jsonl> \\
        --out <results.json>

The outcomes CSV is a read-only extract of
``~/.alphalens/population_ladders/<brief_date>.parquet`` rows for the cohort
window (columns: brief_date, ticker, terminal, matured_at,
market_excess_return, plannable, nonplannable_reason, ...).
"""

from __future__ import annotations

import argparse
import hashlib
import json
import math
import sys
from pathlib import Path

import numpy as np
import pandas as pd

# --- Locked constants (pre-reg §8, §10-§12) ---------------------------------

LABELS_SHA256 = "c8440d40a0c2751717b62f3a83ef2d245957c2a43cd55fbe3405ccdb25bfb95f"
BOOTSTRAP_RESAMPLES = 10_000
BOOTSTRAP_SEED = 20260819
WINSOR_PCT = 0.01
ALPHA_ONE_SIDED = 0.05
TARGET_POWER = 0.80
CONTRAST_LABELS = ("KEPT", "THEME_REFUSED")
KEPT = "KEPT"
REFUSED = "THEME_REFUSED"

# --- Refusal-reason taxonomy (descriptive heuristic, ordered rules) ---------
# Categories per the study plan: non-event rejection vs direction filter vs
# no-transmission-channel vs other. Ordered: event-ness is upstream of
# direction, which is upstream of channel existence.

